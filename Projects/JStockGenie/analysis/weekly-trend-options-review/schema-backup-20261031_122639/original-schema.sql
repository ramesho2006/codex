CREATE TABLE `jstockdata_option_recommendations` (
  `recommendation_id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `review_key` varchar(100) NOT NULL,
  `reviewed_date` date NOT NULL,
  `review_timezone` varchar(50) NOT NULL,
  `source_session_date` date NOT NULL,
  `quote_observed_date` date NOT NULL,
  `scrip` varchar(24) NOT NULL,
  `strategy` varchar(32) NOT NULL,
  `expiry_date` date NOT NULL,
  `dte` smallint NOT NULL,
  `option_type` char(1) NOT NULL,
  `short_strike` decimal(14,4) NOT NULL,
  `long_strike` decimal(14,4) DEFAULT NULL,
  `short_delta_abs` decimal(7,4) NOT NULL,
  `long_delta_abs` decimal(7,4) DEFAULT NULL,
  `contract_quantity` int NOT NULL,
  `contract_multiplier` int NOT NULL,
  `daily_trend` varchar(8) NOT NULL,
  `weekly_trend` varchar(8) NOT NULL,
  `underlying_close` decimal(14,4) NOT NULL,
  `ha_rsi` decimal(8,4) DEFAULT NULL,
  `recommendation_status` varchar(40) NOT NULL,
  `midpoint_credit_usd` decimal(16,4) NOT NULL COMMENT 'Total credit and maximum profit per position',
  `midpoint_max_loss_usd` decimal(16,4) NOT NULL,
  `midpoint_roi_pct` decimal(12,4) NOT NULL,
  `midpoint_breakeven` decimal(14,4) NOT NULL,
  `midpoint_pop_pct` decimal(7,3) NOT NULL COMMENT 'Rounded OptionStrat modeled probability; not delta',
  `midpoint_pol_approx_pct` decimal(7,3) NOT NULL COMMENT '100 minus rounded PoP, not probability of maximum loss',
  `quoted_side_credit_usd` decimal(16,4) NOT NULL COMMENT 'Short bid minus long ask; not guaranteed fill',
  `quoted_side_max_loss_usd` decimal(16,4) NOT NULL,
  `quoted_side_roi_pct` decimal(12,4) NOT NULL,
  `quoted_side_breakeven` decimal(14,4) NOT NULL,
  `csp_cash_collateral_usd` decimal(16,4) DEFAULT NULL,
  `Collateral` decimal(16,4) GENERATED ALWAYS AS ((case when (`strategy` = _utf8mb4'CASH_SECURED_PUT') then ((`short_strike` * `contract_multiplier`) * `contract_quantity`) else ((abs((`short_strike` - `long_strike`)) * `contract_multiplier`) * `contract_quantity`) end)) STORED COMMENT 'USD gross collateral before premium: full strike cash for CSP; strike-width amount for spreads. Not broker-specific buying power.',
  `roi_basis` varchar(24) NOT NULL,
  `earnings_date` date DEFAULT NULL,
  `earnings_in_holding_period` tinyint(1) NOT NULL,
  `legs_json` json NOT NULL,
  `qualifications` text NOT NULL,
  `assumptions_json` json NOT NULL,
  `optionstrat_url` varchar(1000) NOT NULL,
  `source_report_path` varchar(1000) NOT NULL,
  `source_report_sha256` char(64) NOT NULL,
  `snapshot_key` char(64) NOT NULL,
  `payload_sha256` char(64) NOT NULL,
  `inserted_at_utc` datetime(6) NOT NULL DEFAULT (utc_timestamp(6)),
  PRIMARY KEY (`recommendation_id`),
  UNIQUE KEY `uq_option_reco_snapshot` (`snapshot_key`),
  KEY `ix_option_reco_review` (`reviewed_date`,`strategy`),
  KEY `ix_option_reco_symbol` (`scrip`,`reviewed_date`),
  KEY `ix_option_reco_expiry` (`expiry_date`),
  CONSTRAINT `ck_option_reco_contract` CHECK (((`contract_quantity` > 0) and (`contract_multiplier` > 0))),
  CONSTRAINT `ck_option_reco_delta` CHECK (((`short_delta_abs` between 0 and 1) and ((`long_delta_abs` is null) or (`long_delta_abs` between 0 and 1)))),
  CONSTRAINT `ck_option_reco_dte` CHECK ((`dte` = (to_days(`expiry_date`) - to_days(`reviewed_date`)))),
  CONSTRAINT `ck_option_reco_legs` CHECK ((((`strategy` = _utf8mb4'CASH_SECURED_PUT') and (`option_type` = _utf8mb4'P') and (`long_strike` is null) and (`long_delta_abs` is null) and (`csp_cash_collateral_usd` > 0)) or ((`strategy` = _utf8mb4'BULL_PUT_CREDIT_SPREAD') and (`option_type` = _utf8mb4'P') and (`long_strike` < `short_strike`) and (`long_delta_abs` is not null) and (`csp_cash_collateral_usd` is null)) or ((`strategy` = _utf8mb4'BEAR_CALL_CREDIT_SPREAD') and (`option_type` = _utf8mb4'C') and (`long_strike` > `short_strike`) and (`long_delta_abs` is not null) and (`csp_cash_collateral_usd` is null)))),
  CONSTRAINT `ck_option_reco_pop` CHECK (((`midpoint_pop_pct` between 0 and 100) and (`midpoint_pol_approx_pct` = (100 - `midpoint_pop_pct`)))),
  CONSTRAINT `ck_option_reco_strategy` CHECK ((`strategy` in (_utf8mb4'CASH_SECURED_PUT',_utf8mb4'BULL_PUT_CREDIT_SPREAD',_utf8mb4'BEAR_CALL_CREDIT_SPREAD')))
) ENGINE=InnoDB AUTO_INCREMENT=7 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='Historical recommendation snapshots, not executed trades or realized PnL'