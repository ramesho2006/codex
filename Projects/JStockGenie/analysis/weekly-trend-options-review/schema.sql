CREATE TABLE IF NOT EXISTS jstockdata_reco_weekly_optionstrat (
 `reco_id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 `review_date` DATE NOT NULL,
 `scrip` VARCHAR(24) NOT NULL,
 `strategy` VARCHAR(32) NOT NULL,
 `expiry_date` DATE NOT NULL,
 `dte` SMALLINT NOT NULL,
 `short_strike` DECIMAL(14,4) NOT NULL,
 `long_strike` DECIMAL(14,4) NULL,
 `delta_short_leg` DECIMAL(7,4) NOT NULL,
 `delta_long_leg` DECIMAL(7,4) NULL,
 `contract_quantity` INT NOT NULL,
 `daily_trend` VARCHAR(8) NOT NULL,
 `weekly_trend` VARCHAR(8) NOT NULL,
 `underlying_close` DECIMAL(14,4) NOT NULL,
 `ha_rsi` DECIMAL(8,4) NULL,
 `remark` VARCHAR(40) NOT NULL,
 `roi_pct` DECIMAL(12,4) NOT NULL COMMENT 'Midpoint holding-period maximum ROI, not expected return',
 `breakeven` DECIMAL(14,4) NOT NULL COMMENT 'Midpoint strategy breakeven price',
 `pop_pct` DECIMAL(7,3) NOT NULL COMMENT 'OptionStrat modeled midpoint probability of profit',
 `collateral` DECIMAL(16,4) NOT NULL COMMENT 'USD gross collateral before premium; multiplier retained per leg in legs_json',
 `roi_basis` VARCHAR(24) NOT NULL,
 `earnings_date` DATE NULL,
 `earnings_in_holding_period` BOOLEAN NOT NULL,
 `legs_json` JSON NOT NULL,
 `qualifications` TEXT NOT NULL,
 KEY ix_reco_review (review_date,strategy),
 KEY ix_reco_symbol (scrip,review_date),
 KEY ix_reco_expiry (expiry_date),
 CHECK (dte=DATEDIFF(expiry_date,review_date)),
 CHECK (contract_quantity>0 AND collateral>0),
 CHECK (pop_pct BETWEEN 0 AND 100),
 CHECK (delta_short_leg BETWEEN 0 AND 1 AND (delta_long_leg IS NULL OR delta_long_leg BETWEEN 0 AND 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Weekly recommendations; not executed trades';
